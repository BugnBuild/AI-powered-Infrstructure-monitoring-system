"""
Script 3: Split merged pool into train / val / test sets.

Ratios:  Train 70%  |  Val 20%  |  Test 10%

Output:
  ai/dataset/final_dataset/
      train/images/   train/labels/
      val/images/     val/labels/
      test/images/    test/labels/
      data.yaml

Stratified by class distribution so each split has balanced class coverage.
"""

import random
import shutil
from collections import defaultdict
from pathlib import Path
from tqdm import tqdm

# ── Config ───────────────────────────────────────────────────────────────────
SEED        = 42
TRAIN_RATIO = 0.70
VAL_RATIO   = 0.20
TEST_RATIO  = 0.10

CLASS_NAMES = ["Crack", "Pothole", "Surface Erosion"]

BASE_DIR      = Path(__file__).resolve().parents[1]
MERGED_POOL   = BASE_DIR / "dataset" / "merged_pool"
FINAL_DATASET = BASE_DIR / "dataset" / "final_dataset"

POOL_IMAGES = MERGED_POOL / "images"
POOL_LABELS = MERGED_POOL / "labels"


# ── Helpers ──────────────────────────────────────────────────────────────────
def get_primary_class(label_path: Path) -> int:
    """Return the most frequent class ID in a label file (for stratification)."""
    counts = defaultdict(int)
    try:
        with open(label_path) as f:
            for line in f:
                parts = line.strip().split()
                if parts:
                    counts[int(parts[0])] += 1
    except Exception:
        return -1
    return max(counts, key=counts.get) if counts else -1


def make_split_dirs():
    for split in ("train", "val", "test"):
        (FINAL_DATASET / split / "images").mkdir(parents=True, exist_ok=True)
        (FINAL_DATASET / split / "labels").mkdir(parents=True, exist_ok=True)


def copy_split(pairs: list[tuple[Path, Path]], split: str):
    for img_path, lbl_path in tqdm(pairs, desc=f"  Copying {split:5s}"):
        shutil.copy2(img_path, FINAL_DATASET / split / "images" / img_path.name)
        shutil.copy2(lbl_path, FINAL_DATASET / split / "labels" / lbl_path.name)


def write_yaml():
    yaml_content = f"""# Smart Civic AI — Road Damage Detection
# Auto-generated by scripts/3_split_dataset.py

path: {FINAL_DATASET.as_posix()}
train: train/images
val:   val/images
test:  test/images

nc: {len(CLASS_NAMES)}
names: {CLASS_NAMES}
"""
    yaml_path = FINAL_DATASET / "data.yaml"
    yaml_path.write_text(yaml_content)
    print(f"[YAML] Written: {yaml_path}")
    return yaml_path


# ── Main ─────────────────────────────────────────────────────────────────────
def main():
    print("=" * 60)
    print("  Smart Civic AI — Train / Val / Test Split")
    print("=" * 60)

    if not POOL_IMAGES.exists():
        print("[ERROR] Merged pool not found. Run script 2 first.")
        return

    img_exts = {".jpg", ".jpeg", ".png"}
    all_images = sorted([p for p in POOL_IMAGES.iterdir() if p.suffix.lower() in img_exts])

    # Filter to only images that have a matching label
    valid_pairs: list[tuple[Path, Path]] = []
    for img in all_images:
        lbl = POOL_LABELS / (img.stem + ".txt")
        if lbl.exists():
            valid_pairs.append((img, lbl))

    print(f"[INFO] Total valid image-label pairs: {len(valid_pairs):,}")

    if len(valid_pairs) == 0:
        print("[ERROR] No valid pairs found. Check merged_pool/images and labels.")
        return

    # ── Stratified shuffle ──────────────────────────────────────────────────
    random.seed(SEED)

    # Group by primary class
    class_buckets: dict[int, list] = defaultdict(list)
    for pair in valid_pairs:
        cls = get_primary_class(pair[1])
        class_buckets[cls].append(pair)

    train_pairs, val_pairs, test_pairs = [], [], []

    for cls_id, pairs in sorted(class_buckets.items()):
        random.shuffle(pairs)
        n       = len(pairs)
        n_train = int(n * TRAIN_RATIO)
        n_val   = int(n * VAL_RATIO)
        # Remaining goes to test
        train_pairs.extend(pairs[:n_train])
        val_pairs.extend(pairs[n_train : n_train + n_val])
        test_pairs.extend(pairs[n_train + n_val :])

    # Final shuffle within each split
    random.shuffle(train_pairs)
    random.shuffle(val_pairs)
    random.shuffle(test_pairs)

    print(f"\n  Split sizes:")
    print(f"    Train : {len(train_pairs):,}  ({len(train_pairs)/len(valid_pairs)*100:.1f}%)")
    print(f"    Val   : {len(val_pairs):,}  ({len(val_pairs)/len(valid_pairs)*100:.1f}%)")
    print(f"    Test  : {len(test_pairs):,}  ({len(test_pairs)/len(valid_pairs)*100:.1f}%)")

    # ── Print class distribution per split ──────────────────────────────────
    print("\n  Class distribution:")
    for split_name, pairs in [("train", train_pairs), ("val", val_pairs), ("test", test_pairs)]:
        cls_counts = defaultdict(int)
        for _, lbl in pairs:
            with open(lbl) as f:
                for line in f:
                    parts = line.strip().split()
                    if parts:
                        cls_counts[int(parts[0])] += 1
        total_ann = sum(cls_counts.values())
        parts_str = "  ".join(
            f"{CLASS_NAMES[i]}: {cls_counts.get(i, 0):,}"
            for i in range(len(CLASS_NAMES))
        )
        print(f"    {split_name:5s} | Total annotations: {total_ann:,} | {parts_str}")

    # ── Copy files ───────────────────────────────────────────────────────────
    make_split_dirs()
    print()
    copy_split(train_pairs, "train")
    copy_split(val_pairs,   "val")
    copy_split(test_pairs,  "test")

    yaml_path = write_yaml()

    # ── Verify counts ────────────────────────────────────────────────────────
    for split in ("train", "val", "test"):
        n_imgs = len(list((FINAL_DATASET / split / "images").iterdir()))
        n_lbls = len(list((FINAL_DATASET / split / "labels").iterdir()))
        print(f"  [VERIFY] {split:5s} → {n_imgs:,} images, {n_lbls:,} labels")

    print(f"\n[DONE] Final dataset ready at: {FINAL_DATASET}")
    print(f"[YAML] Use this path in training: {yaml_path}")
    print("\nNext step → Run: python scripts/4_train_yolo.py")


if __name__ == "__main__":
    main()
